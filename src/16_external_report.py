import os

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


# Load stage-1 external validation results
spec = pd.read_csv(
    "results/tables/hirisa_specificity.csv"
)

resp = pd.read_csv(
    "results/tables/hirisa_external_response.csv"
)

verdicts = pd.read_csv(
    "results/external/h5_verdicts.csv"
)

cells = pd.read_csv(
    "results/external/hirisa_stage1_cells.csv"
)


# Primary comparison: CD14 monocytes, IFN-alpha vs IFN-gamma
primary = spec[
    (spec.cell_set == "primary_CD14Mono")
    & (spec.type1_stimulus == "IFNa")
]

v = (
    verdicts[
        (verdicts.cell_set == "primary_CD14Mono")
        & (verdicts.type1_stimulus == "IFNa")
    ]
    .set_index("comparison")
)


h5 = v.loc[
    "H5: D2 vs D",
    "criterion_met"
]

baseline_a = v.loc[
    "H5-baseline (a): D2 vs A",
    "criterion_met"
]

baseline_a2 = v.loc[
    "H5-baseline (b): D2 vs A2",
    "criterion_met"
]

credit = v.loc[
    "credit rule: Δ_split >= Δ_net -> credit decomposition",
    "criterion_met"
]


S = primary.pivot(
    index="donor",
    columns="representation",
    values="SEP"
)[
    ["D", "D2", "A", "A2"]
]


delta_network = np.median(
    S.D2 - S.D
)

delta_split = np.median(
    S.A2 - S.A
)


# Interpret the pre-specified decision rule
if h5 and baseline_a and baseline_a2:

    headline = (
        "D2 separates IFN-alpha from IFN-gamma better than D "
        "and better than both gene-set-average baselines."
    )

elif h5 and credit:

    headline = (
        "D2 separates IFN-alpha from IFN-gamma better than "
        "the original model D, but the plain average of the "
        "decomposed gene sets (A2) separates them even better. "
        "The improvement is therefore attributed to the gene-set "
        "decomposition rather than the neural network."
    )

elif h5:

    headline = (
        "D2 beats D but fails at least one baseline criterion."
    )

else:

    headline = (
        "D2 does not separate IFN-alpha from IFN-gamma "
        "better than D."
    )


lines = [
    "# External validation (HIRISA, GSE306664) - stage 1, CD14 monocytes",
    "",
    "_Generated by `src/16_external_report.py`. "
    "The external validation design and decision rules were "
    "pre-specified before scoring the HIRISA data._",
    "",
    "## Pre-specified verdict",
    "",
    f"**{headline}**",
    "",
    "| Comparison | donors better | median SEP difference | criterion met |",
    "|---|---:|---:|---|"
]


for comparison in [
    "H5: D2 vs D",
    "H5-baseline (a): D2 vs A",
    "H5-baseline (b): D2 vs A2",
    "context: A2 vs A (split, no network)"
]:

    row = v.loc[comparison]

    lines.append(
        f"| {comparison} "
        f"| {int(row.n_donors_better)}/{int(row.n_donors)} "
        f"| {row.median_difference:+.3f} "
        f"| {'yes' if row.criterion_met else 'no'} |"
    )


lines += [
    "",
    (
        f"Credit rule: "
        f"delta_network = median(SEP_D2 - SEP_D) = {delta_network:+.3f}; "
        f"delta_split = median(SEP_A2 - SEP_A) = {delta_split:+.3f}. "
        f"Because delta_split "
        f"{'>=' if credit else '<'} delta_network, "
        f"the improvement is credited to "
        f"**{'the gene-set decomposition' if credit else 'the network'}**."
    ),
    "",
    (
        "D = original pathway autoencoder; "
        "D2 = overlap-aware autoencoder; "
        "A = average of the original IFN gene sets; "
        "A2 = average of the shared/unique split gene sets."
    ),
    "",
    "## Separation index per donor",
    "",
    S.round(3).reset_index().to_markdown(index=False),
    ""
]


# Show the two components of the separation score
for column, title in [
    (
        "alpha_specificity",
        "Alpha-specificity = response(alpha | IFN-alpha) "
        "- response(alpha | IFN-gamma)"
    ),
    (
        "gamma_specificity",
        "Gamma-specificity = response(gamma | IFN-gamma) "
        "- response(gamma | IFN-alpha)"
    )
]:

    values = primary.pivot(
        index="donor",
        columns="representation",
        values=column
    )[
        ["D", "D2", "A", "A2"]
    ]

    lines += [
        f"### {title}",
        "",
        values.round(3).reset_index().to_markdown(index=False),
        ""
    ]


# Secondary robustness analyses from stage 1
secondary = verdicts[
    verdicts.role.str.startswith("secondary")
][
    [
        "cell_set",
        "type1_stimulus",
        "comparison",
        "n_donors_better",
        "n_donors",
        "median_difference",
        "criterion_met"
    ]
]


lines += [
    "## Robustness checks",
    "",
    secondary.round(3).to_markdown(index=False),
    "",
    "## Transport of the original pathway units",
    "",
]


transport = (
    resp[
        resp.cell_set == "primary_CD14Mono"
    ]
    .groupby(
        [
            "representation",
            "unit",
            "treatment"
        ]
    )
    .response
    .agg(
        lambda x:
            f"{x.median():.2f} "
            f"[{x.min():.2f}, {x.max():.2f}]"
    )
    .unstack("treatment")
    .reset_index()
)


lines += [
    transport.to_markdown(index=False),
    "",
    "## Cells used",
    "",
    cells.to_markdown(index=False),
    "",
    "## Notes and caveats",
    "",
    "- Five donors; verdicts use the pre-specified donor-count and median rule rather than p-values.",
    "- Kang and HIRISA differ in donor population, assay platform and stimulation design, so absolute transport differences are expected.",
    "- Specificity uses within-donor treatment-versus-control contrasts.",
    "- Stage 2 tests B, NK and T cells as secondary replication; the stage-1 verdict remains unchanged.",
    ""
]


os.makedirs(
    "results/external",
    exist_ok=True
)

with open(
    "results/external/external_results.md",
    "w",
    encoding="utf-8"
) as f:

    f.write(
        "\n".join(lines)
        + "\n"
    )


# Figure 8: donor-level external specificity
colors = {
    "D": "#2a78d6",
    "D2": "#6250d6",
    "A": "#eb6834",
    "A2": "#1baf7a"
}

order = [
    "A",
    "D",
    "D2",
    "A2"
]

plt.rcParams.update({
    "font.size": 9,
    "axes.spines.top": False,
    "axes.spines.right": False,
    "axes.grid": True,
    "grid.color": "#e4e3df",
    "axes.axisbelow": True,
    "legend.frameon": False
})


fig, axes = plt.subplots(
    1,
    3,
    figsize=(17,7),
    gridspec_kw={"wspace": 0.35}
)


for ax, column, title in zip(
    axes,
    [
        "SEP",
        "alpha_specificity",
        "gamma_specificity"
    ],
    [
        "Separation index",
        "Alpha-specificity",
        "Gamma-specificity"
    ]
):

    table = primary.pivot(
        index="donor",
        columns="representation",
        values=column
    )[order]


    # Connect the four representations for each donor
    for _, row in table.iterrows():

        ax.plot(
            range(len(order)),
            row.values,
            color="#c9c8c3",
            lw=0.8,
            zorder=1
        )


    for i, model in enumerate(order):

        ax.scatter(
            [i] * len(table),
            table[model],
            color=colors[model],
            s=28,
            zorder=2
        )

        ax.plot(
            [i - 0.2, i + 0.2],
            [table[model].median()] * 2,
            color="#0b0b0b",
            lw=1.5,
            zorder=3
        )


    ax.axhline(
        0,
        color="#52514e",
        lw=0.8
    )

    labels = {
    "A": "A\noriginal\nset avg",
    "D": "D\npathway AE",
    "D2": "D2\noverlap-aware",
    "A2": "A2\nsplit\nset avg"
}

    ax.set_xticks(
        range(len(order)),
        [labels[m] for m in order],
        fontsize=7.5
    )

    ax.set_title(
        title,
        loc="left"
    )


axes[0].set_ylabel(
    "Kang-SD units\n(higher = more specific)"
)


fig.suptitle(
    "HIRISA CD14 monocytes, IFN-alpha vs IFN-gamma: "
    "each line = one donor (n = 5); bar = median",
    x=0.01,
    ha="left"
)


fig.text(
    0.01,
    -0.03,
    f"Verdict: {headline}",
    color="#52514e",
    wrap=True,
    fontsize=8
)


os.makedirs(
    "figures",
    exist_ok=True
)

fig.savefig(
    "figures/fig8_hirisa_external_specificity.png",
    dpi=150,
    bbox_inches="tight"
)

plt.close(fig)


print(headline)

print(
    f"D2 - D median SEP difference: "
    f"{delta_network:+.3f}"
)

print(
    f"A2 - A median SEP difference: "
    f"{delta_split:+.3f}"
)

print(
    "Saved results/external/external_results.md"
)

print(
    "Saved figures/fig8_hirisa_external_specificity.png"
)