import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


# Combine stage-1 and stage-2 specificity results
stage1 = (
    pd.read_csv(
        "results/tables/hirisa_specificity.csv"
    )
    .query(
        "cell_set == 'primary_CD14Mono'"
    )
)

stage1 = stage1.assign(
    cell_type="CD14 Mono (stage 1, primary)",
    cell_set="primary"
)


stage2 = (
    pd.read_csv(
        "results/tables/"
        "hirisa_stage2_specificity.csv"
    )
    .query(
        "cell_set == 'primary_lineage'"
    )
)

stage2 = stage2.assign(
    cell_type=stage2.cell_type.map({
        "Bcell": "B (stage 2)",
        "NK": "NK (stage 2)",
        "Tcell": "T (stage 2)"
    }),
    cell_set="primary"
)


spec = pd.concat(
    [stage1, stage2],
    ignore_index=True
)


# Combine stage-1 and stage-2 verdict tables
v1 = (
    pd.read_csv(
        "results/external/h5_verdicts.csv"
    )
    .query(
        "cell_set == 'primary_CD14Mono'"
    )
    .assign(
        cell_type=
            "CD14 Mono (stage 1, primary)",
        donors="all donors"
    )
)


v2 = (
    pd.read_csv(
        "results/external/"
        "h5_stage2_verdicts.csv"
    )
    .query(
        "cell_set == 'primary_lineage'"
    )
)

v2 = v2.assign(
    cell_type=v2.cell_type.map({
        "Bcell": "B (stage 2)",
        "NK": "NK (stage 2)",
        "Tcell": "T (stage 2)"
    })
)


verdicts = pd.concat(
    [v1, v2],
    ignore_index=True
)


cell_order = [
    "CD14 Mono (stage 1, primary)",
    "B (stage 2)",
    "NK (stage 2)",
    "T (stage 2)"
]


comparisons = [
    "H5: D2 vs D",
    "H5-baseline (a): D2 vs A",
    "H5-baseline (b): D2 vs A2",
    "context: A2 vs A (split, no network)"
]


def verdict_cell(row):

    return (
        f"{'yes' if row.criterion_met else 'no'} "
        f"({int(row.n_donors_better)}/"
        f"{int(row.n_donors)}, "
        f"{row.median_difference:+.2f})"
    )


# Build the verdict grid across cell types
grid_rows = []

for type1 in [
    "IFNa",
    "IFNb"
]:

    table = verdicts[
        (verdicts.type1_stimulus == type1)
        & (verdicts.donors == "all donors")
    ]


    for comparison in comparisons:

        row = {
            "type-I stimulus": type1,
            "comparison": comparison
        }


        for cell_type in cell_order:

            result = table[
                (table.cell_type == cell_type)
                & (
                    table.comparison
                    == comparison
                )
            ]

            row[cell_type] = (
                verdict_cell(
                    result.iloc[0]
                )
                if len(result)
                else ""
            )


        grid_rows.append(row)


grid = pd.DataFrame(
    grid_rows
)


# B-cell sensitivity analysis without donor 3491BW
sensitivity = v2[
    (v2.donors != "all donors")
    & (
        v2.type1_stimulus
        == "IFNa"
    )
][
    [
        "comparison",
        "n_donors_better",
        "n_donors",
        "median_difference",
        "criterion_met"
    ]
]


# Robustness using all QC cells instead of lineage-labelled cells
all_cells = (
    pd.read_csv(
        "results/external/"
        "h5_stage2_verdicts.csv"
    )
    .query(
        "cell_set == 'secondary_all_cells' "
        "and donors == 'all donors' "
        "and type1_stimulus == 'IFNa'"
    )
)[
    [
        "cell_type",
        "comparison",
        "n_donors_better",
        "n_donors",
        "median_difference",
        "criterion_met"
    ]
]


# Median specificity components for IFN-alpha
medians = (
    spec[
        spec.type1_stimulus
        == "IFNa"
    ]
    .groupby(
        [
            "cell_type",
            "representation"
        ]
    )[
        [
            "alpha_specificity",
            "gamma_specificity",
            "SEP"
        ]
    ]
    .median()
    .round(2)
    .unstack("representation")
)


# Original model D responses in stage-2 cell types
responses = (
    pd.read_csv(
        "results/tables/"
        "hirisa_stage2_response.csv"
    )
    .query(
        "cell_set == 'primary_lineage' "
        "and representation == 'D'"
    )
)


response_table = (
    responses.groupby(
        [
            "cell_type",
            "unit",
            "treatment"
        ]
    )
    .response
    .median()
    .unstack("treatment")
    .round(2)
    .reset_index()
)


# Append stage-2 results to the external report
lines = [
    "",
    "---",
    "",
    "# Stage 2 — B, NK and T cells "
    "(secondary / confirmatory robustness)",
    "",
    "_Generated by `src/18_external_stage2_report.py`. "
    "Stage 2 uses the same frozen Kang-trained models, scaler, "
    "reference SDs, specificity formula, decision rule and credit "
    "rule as stage 1. The stage-1 result is unchanged._",
    "",
    "## Verdict grid across all four cell types "
    "(primary cells; all 5 donors)",
    "",
    "Each cell: criterion met? "
    "(donors better / donors, median SEP difference).",
    "",
    grid.to_markdown(index=False),
    "",
    "## Reading",
    "",
    "- **D2 vs D does not replicate outside monocytes.** "
    "In B, NK and T cells, D2 separates IFN-alpha from "
    "IFN-gamma worse than D in every donor.",
    "",
    "- **The neural overlap-aware model never beats A2** "
    "in any of the four cell types.",
    "",
    "- **The shared/unique decomposition itself helps consistently:** "
    "A2 beats A in every donor of every cell type.",
    "",
    "- The difference between cell types is descriptive. "
    "No biological mechanism is claimed from these results alone.",
    "",
    "## Median specificity components "
    "(primary cells, IFN-alpha as type-I)",
    "",
    medians.reset_index().to_markdown(index=False),
    "",
    "## Stage-2 responses of the original D units "
    "(median over donors, Kang-SD units)",
    "",
    response_table.to_markdown(index=False),
    "",
    "## Robustness",
    "",
    "B cells without donor 3491BW "
    "(its IFN-gamma sample has no same-pool control):",
    "",
    sensitivity.round(3).to_markdown(index=False),
    "",
    "All QC cells instead of lineage-labelled cells "
    "(IFN-alpha):",
    "",
    all_cells.round(3).to_markdown(index=False),
    "",
    "IFN-beta results are shown in the verdict grid above.",
    ""
]


with open(
    "results/external/external_results.md",
    "a",
    encoding="utf-8"
) as f:

    f.write(
        "\n".join(lines)
        + "\n"
    )


# Figure 9: donor-level specificity across all four cell types
colors = {
    "D": "#2a78d6",
    "D2": "#6250d6",
    "A": "#eb6834",
    "A2": "#1baf7a"
}


labels = {
    "A": "A\nset avg\n(original)",
    "D": "D\npathway\nAE",
    "D2": "D2\noverlap-\naware AE",
    "A2": "A2\nset avg\n(split)"
}


model_order = [
    "A",
    "D",
    "D2",
    "A2"
]


plt.rcParams.update({
    "font.size": 9,
    "axes.spines.top": False,
    "axes.spines.right": False,
    "axes.grid": True,
    "grid.color": "#e4e3df",
    "axes.axisbelow": True
})


fig, axes = plt.subplots(
    1,
    4,
    figsize=(15, 4.3),
    sharey=True,
    gridspec_kw={"wspace": 0.15}
)


for ax, cell_type in zip(
    axes,
    cell_order
):

    table = (
        spec[
            (spec.cell_type == cell_type)
            & (
                spec.type1_stimulus
                == "IFNa"
            )
        ]
        .pivot(
            index="donor",
            columns="representation",
            values="SEP"
        )[model_order]
    )


    # Connect representations from the same donor
    for _, row in table.iterrows():

        ax.plot(
            range(4),
            row.values,
            color="#c9c8c3",
            lw=0.8,
            zorder=1
        )


    for i, model in enumerate(
        model_order
    ):

        ax.scatter(
            [i] * len(table),
            table[model],
            color=colors[model],
            s=26,
            zorder=2
        )

        ax.plot(
            [i - 0.2, i + 0.2],
            [table[model].median()] * 2,
            color="#0b0b0b",
            lw=1.5,
            zorder=3
        )


    ax.axhline(
        0,
        color="#52514e",
        lw=0.8
    )


    ax.set_xticks(
        range(4),
        [
            labels[m]
            for m in model_order
        ],
        fontsize=7.5
    )


    h5 = verdicts[
        (verdicts.cell_type == cell_type)
        & (
            verdicts.type1_stimulus
            == "IFNa"
        )
        & (
            verdicts.donors
            == "all donors"
        )
        & (
            verdicts.comparison
            == "H5: D2 vs D"
        )
    ].iloc[0]


    ax.set_title(
        f"{cell_type}\n"
        f"D2 > D: "
        f"{int(h5.n_donors_better)}/"
        f"{int(h5.n_donors)} donors",
        loc="left",
        fontsize=9
    )


axes[0].set_ylabel(
    "Separation index, IFN-alpha vs IFN-gamma\n"
    "(Kang-SD units; higher = more specific)"
)


fig.suptitle(
    "HIRISA external validation across cell types: "
    "each line = one donor (n = 5); bar = median",
    x=0.01,
    ha="left",
    y=1.07
)


fig.text(
    0.01,
    -0.10,
    "A2 beats A in every donor of every cell type; "
    "D2 beats D only in monocytes and never beats A2.",
    color="#52514e",
    fontsize=8
)


fig.savefig(
    "figures/fig9_hirisa_all_cell_types.png",
    dpi=150,
    bbox_inches="tight"
)

plt.close(fig)


print(
    grid.to_string(index=False)
)

print(
    "Appended stage 2 to "
    "results/external/external_results.md"
)

print(
    "Saved figures/"
    "fig9_hirisa_all_cell_types.png"
)